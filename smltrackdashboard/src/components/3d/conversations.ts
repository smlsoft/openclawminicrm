export function generateAllConversations(): { name: string; conv: Conversation }[] {
  const all: { name: string; conv: Conversation }[] = [];
  for (const tpl of TEMPLATES) {
    for (const name of NAMES) {
      all.push({
        name,
        conv: { turns: tpl.turns.map(t => t.replace(/\{name\}/g, name)) },
      });
    }
  }
  return all;
}

